-- 004 — organizer controls, email credentials and gateway payments.
--
-- Additive only. Existing users, events, registrations, passes and payments keep
-- their IDs and data. Every statement is re-runnable so a partially applied
-- migration is recoverable.

-- ------------------------------------------------------- platform-wide switch

CREATE TABLE IF NOT EXISTS platform_settings (
  id                       SMALLINT PRIMARY KEY,
  event_discovery_enabled  BOOLEAN NOT NULL DEFAULT TRUE,
  updated_by               BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO platform_settings (id, event_discovery_enabled)
VALUES (1, TRUE)
ON CONFLICT (id) DO NOTHING;

-- ------------------------------------------- single-use account credentials

-- Only the SHA-256 hash of a verification or reset token is stored. The raw
-- token exists once, in the email, and is never written to the database or a
-- log line.
CREATE TABLE IF NOT EXISTS auth_tokens (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose     TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
  token_hash  TEXT NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  used_at     TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS auth_tokens_user_idx ON auth_tokens (user_id, purpose, created_at DESC);

-- ------------------------------------------------------------- gateway fields

ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider TEXT NOT NULL DEFAULT 'manual';
ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider_order_id   TEXT;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider_payment_id TEXT;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider_signature   TEXT;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS provider_payload     JSONB;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS paid_at              TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS payments_provider_order_key
  ON payments (provider_order_id) WHERE provider_order_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS payments_provider_payment_key
  ON payments (provider_payment_id) WHERE provider_payment_id IS NOT NULL;

-- Webhook delivery is at-least-once. The provider's event id is the idempotency
-- key, so a repeated delivery cannot confirm a registration twice.
CREATE TABLE IF NOT EXISTS payment_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider    TEXT NOT NULL DEFAULT 'razorpay',
  event_key   TEXT NOT NULL UNIQUE,
  event_type  TEXT,
  payment_id  BIGINT REFERENCES payments(id) ON DELETE SET NULL,
  payload     JSONB NOT NULL DEFAULT '{}'::jsonb,
  received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS payment_events_payment_idx ON payment_events (payment_id);
