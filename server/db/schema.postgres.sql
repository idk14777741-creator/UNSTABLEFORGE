-- UNSTABLE FORGE — PostgreSQL schema.
--
-- This schema mirrors the SQLite schema the application has always used, so the
-- SQLite → PostgreSQL migration can preserve every ID, relationship, timestamp
-- and password hash without changing application behaviour.
--
-- It is applied idempotently at startup by server/db/index.js and again by
-- scripts/migrate-sqlite-to-postgres.mjs inside a transaction.
--
-- The multi-event platform schema (events configuration, participants, teams,
-- payments, passes, certificates, media) is planned separately in
-- docs/PLATFORM_EVOLUTION.md and will arrive as additive migrations.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version    TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL,
  tagline    TEXT,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'participant'
                CHECK (role IN ('participant', 'organizer', 'admin')),
  created_at    TIMESTAMPTZ NOT NULL
);

-- Google (and future provider) identities. A row links a provider subject to a
-- local account; the local user id is what everything else references.
CREATE TABLE IF NOT EXISTS oauth_accounts (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider         TEXT NOT NULL CHECK (provider IN ('google')),
  provider_user_id TEXT NOT NULL,
  email            TEXT NOT NULL,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_user_id),
  UNIQUE (user_id, provider)
);
CREATE INDEX IF NOT EXISTS idx_oauth_accounts_email ON oauth_accounts (lower(email));

CREATE TABLE IF NOT EXISTS announcements (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id     BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  slug         TEXT NOT NULL UNIQUE,
  content      TEXT NOT NULL,
  category     TEXT NOT NULL,
  published_at TIMESTAMPTZ,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ NOT NULL,
  updated_at   TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_announcements_public
  ON announcements (is_published, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_announcements_event
  ON announcements (event_id);
CREATE INDEX IF NOT EXISTS idx_announcements_category
  ON announcements (category);

CREATE TABLE IF NOT EXISTS registrations (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id   BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  full_name  TEXT NOT NULL,
  campus     TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  UNIQUE (user_id, event_id)
);

CREATE INDEX IF NOT EXISTS idx_registrations_event
  ON registrations (event_id, created_at DESC);

CREATE TABLE IF NOT EXISTS projects (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id        BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title           TEXT NOT NULL,
  slug            TEXT NOT NULL UNIQUE,
  tagline         TEXT NOT NULL,
  description     TEXT NOT NULL,
  category        TEXT NOT NULL,
  technologies    JSONB NOT NULL DEFAULT '[]'::jsonb,
  team_name       TEXT,
  repo_url        TEXT,
  demo_url        TEXT,
  cover_image_url TEXT,
  status          TEXT NOT NULL DEFAULT 'draft'
                  CHECK (status IN ('draft', 'submitted', 'published', 'rejected')),
  created_at      TIMESTAMPTZ NOT NULL,
  updated_at      TIMESTAMPTZ NOT NULL,
  published_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_projects_public
  ON projects (status, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_projects_event
  ON projects (event_id);
CREATE INDEX IF NOT EXISTS idx_projects_owner
  ON projects (user_id);

INSERT INTO schema_migrations (version)
VALUES ('001_sqlite_parity')
ON CONFLICT (version) DO NOTHING;
